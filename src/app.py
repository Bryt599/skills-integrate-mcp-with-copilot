class LoginData(BaseModel):
    username: str
    password: str


def load_teacher_credentials():
    config_path = current_dir / "teachers.json"
    if not config_path.exists():
        raise RuntimeError("Missing teachers.json configuration file")

    with open(config_path, "r", encoding="utf-8") as file:
        data = json.load(file)

    return data.get("teachers", [])


teachers = load_teacher_credentials()
active_sessions = {}


def verify_teacher_credentials(username: str, password: str) -> bool:
    for teacher in teachers:
        if hmac.compare_digest(teacher.get("username", ""), username) and hmac.compare_digest(teacher.get("password", ""), password):
            return True
    return False


def get_current_teacher(request: Request) -> str:
    auth_header = request.headers.get("Authorization")
    if not auth_header or not auth_header.startswith("Bearer "):
        raise HTTPException(status_code=401, detail="Teacher login required")

    token = auth_header.split(" ", 1)[1]
    username = active_sessions.get(token)
    if not username:
        raise HTTPException(status_code=401, detail="Invalid or expired token")

    return username


@app.get("/")
def root():
    return RedirectResponse(url="/static/index.html")


@app.get("/activities")
def get_activities():
    return activities


@app.post("/login")
def login(data: LoginData):
    if not verify_teacher_credentials(data.username, data.password):
        raise HTTPException(status_code=401, detail="Invalid username or password")

    token = secrets.token_hex(16)
    active_sessions[token] = data.username
    return {"token": token, "username": data.username}


@app.post("/logout")
def logout(request: Request):
    auth_header = request.headers.get("Authorization")
    if auth_header and auth_header.startswith("Bearer "):
        token = auth_header.split(" ", 1)[1]
        active_sessions.pop(token, None)

    return {"message": "Logged out"}


@app.get("/me")
def current_teacher(request: Request):
    username = get_current_teacher(request)
    return {"username": username}


@app.post("/activities/{activity_name}/signup")
def signup_for_activity(activity_name: str, email: str):
    """Sign up a student for an activity"""
    # Validate activity exists
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    # Get the specific activity
    activity = activities[activity_name]

    # Validate student is not already signed up
    if email in activity["participants"]:
        raise HTTPException(
            status_code=400,
            detail="Student is already signed up"
        )

    # Add student
    activity["participants"].append(email)
    return {"message": f"Signed up {email} for {activity_name}"}


@app.delete("/activities/{activity_name}/unregister")
def unregister_from_activity(activity_name: str, email: str, request: Request):
    """Unregister a student from an activity"""
    get_current_teacher(request)

    # Validate activity exists
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    # Get the specific activity
    activity = activities[activity_name]

    # Validate student is signed up
    if email not in activity["participants"]:
        raise HTTPException(
            status_code=400,
            detail="Student is not signed up for this activity"
        )

    # Remove student
    activity["participants"].remove(email)
    return {"message": f"Unregistered {email} from {activity_name}"}
